    #[test]
    fn test_gbk_roundtrip() {
        let sequence = "ATGCATGCATGC".to_string();
        let annotations = vec![Annotation {
            id: "test-feat".to_string(),
            name: "TestFeat".to_string(),
            feature_type: "misc_feature".to_string(),
            start: 2, // 0-indexed: "GC"
            end: 4,
            strand: Strand::Forward,
            color: None,
            display_shape: None,
        }];
        let primers = vec![crate::models::Primer {
            id: "test-primer".to_string(),
            name: "TestPrimer".to_string(),
            sequence: "ATGC".to_string(),
            start: 0,
            end: 4,
            strand: Strand::Forward,
            tail_5: "".to_string(),
            tail_3: "".to_string(),
            color: None,
            mismatches: vec![],
        }];

        let test_path = "../test_roundtrip.gbk".to_string();

        // Export
        export_gbk(
            test_path.clone(),
            sequence.clone(),
            annotations.clone(),
            primers.clone(),
            Topology::Linear,
        )
        .expect("Export failed");

        // Import
        let imported = list_gbk_sequences(test_path.clone()).expect("Import failed");

        let imp_seq = &imported[0];
        assert_eq!(imp_seq.sequence, sequence);

        let imp_feat = imp_seq
            .annotations
            .iter()
            .find(|a| a.name == "TestFeat")
            .unwrap();
        assert_eq!(imp_feat.start, 2);
        assert_eq!(imp_feat.end, 4);

        let imp_primer = imp_seq
            .primers
            .iter()
            .find(|a| a.name == "TestPrimer")
            .unwrap();
        assert_eq!(imp_primer.start, 0);
        assert_eq!(imp_primer.end, 4);
        assert_eq!(imp_primer.sequence, "ATGC");

        // Cleanup
        let _ = std::fs::remove_file(test_path);
    }

