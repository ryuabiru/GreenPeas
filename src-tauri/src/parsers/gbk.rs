    #[test]
    fn circular_genbank_edit_undo_redo_save_reload_preserves_document_data() {
        use crate::algorithms::primer::reanalyze_all_primers;
        use crate::algorithms::sequence::{apply_edit, EditOp};

        let path = std::env::temp_dir().join(format!(
            "greenpeas-circular-edit-roundtrip-{}.gbk",
            std::process::id()
        ));
        let path_string = path.to_string_lossy().into_owned();
        let sequence = "ACGTACGTACGT".to_string();
        let annotations = vec![Annotation {
            id: "origin-feature".into(),
            name: "OriginFeature".into(),
            feature_type: "misc_feature".into(),
            start: 9,
            end: 3,
            strand: Strand::Reverse,
            color: Some("#336699".into()),
            display_shape: Some(DisplayShape::Arrow),
        }];
        let primers = vec![crate::models::Primer {
            id: "origin-primer".into(),
            name: "OriginPrimer".into(),
            sequence: "ACGT".into(),
            start: 10,
            end: 2,
            strand: Strand::Forward,
            tail_5: String::new(),
            tail_3: String::new(),
            color: Some("#aa5500".into()),
            mismatches: Vec::new(),
        }];
        export_gbk(
            path_string.clone(),
            sequence.clone(),
            annotations,
            primers,
            Topology::Circular,
        )
        .unwrap();
        let opened = list_gbk_sequences(path_string.clone()).unwrap().remove(0);
        assert_eq!(opened.topology, Topology::Circular);
        assert_eq!(opened.primers.len(), 1);
        assert_eq!(opened.primers[0].name, "OriginPrimer");

        let after_insert = apply_edit(
            opened.clone(),
            EditOp::Insert {
                pos: 0,
                sequence: "GG".into(),
            },
        )
        .unwrap();
        let after_delete =
            apply_edit(after_insert.clone(), EditOp::Delete { pos: 0, len: 2 }).unwrap();
        assert_eq!(after_insert.sequence, "GGACGTACGTACGT");
        assert_eq!(after_delete.sequence, sequence);

        // Exercise the same snapshot transitions used by the UI store.
        let mut current = after_delete;
        let mut history = vec![opened.clone(), after_insert.clone()];
        let mut redo_stack = Vec::new();
        redo_stack.push(current.clone());
        current = history.pop().unwrap();
        assert_eq!(current.sequence, after_insert.sequence);
        current = redo_stack.pop().unwrap();
        let mut redone = current;
        reanalyze_all_primers(&redone.sequence, &mut redone.primers);
        assert_eq!(redone.sequence, sequence);
        assert_eq!(redone.annotations[0].start, 9);
        assert_eq!(redone.annotations[0].end, 3);
        assert_eq!(redone.primers[0].start, 10);
        assert_eq!(redone.primers[0].end, 2);

        export_gbk(
            path_string.clone(),
            redone.sequence.clone(),
            redone.annotations.clone(),
            redone.primers.clone(),
            redone.topology.clone(),
        )
        .unwrap();
        let reloaded = list_gbk_sequences(path_string.clone()).unwrap().remove(0);
        let _ = std::fs::remove_file(path);
        assert_eq!(reloaded.sequence, redone.sequence);
        assert_eq!(reloaded.topology, redone.topology);
        assert_eq!(reloaded.annotations.len(), 1);
        assert_eq!(reloaded.annotations[0].name, "OriginFeature");
        assert_eq!(reloaded.annotations[0].start, 9);
        assert_eq!(reloaded.annotations[0].end, 3);
        assert_eq!(reloaded.annotations[0].strand, Strand::Reverse);
        assert_eq!(reloaded.annotations[0].color, Some("#336699".into()));
        assert_eq!(reloaded.primers.len(), 1);
        assert_eq!(reloaded.primers[0].name, "OriginPrimer");
        assert_eq!(reloaded.primers[0].start, 10);
        assert_eq!(reloaded.primers[0].end, 2);
        assert_eq!(reloaded.primers[0].strand, Strand::Forward);
        assert_eq!(reloaded.primers[0].sequence, "ACGT");
        assert_eq!(reloaded.primers[0].mismatches, redone.primers[0].mismatches);
        assert_eq!(reloaded.primers[0].color, Some("#aa5500".into()));
    }

