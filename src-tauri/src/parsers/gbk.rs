//! 学習メモ: GenBank形式の読込と書出し、およびfeature座標の変換を実装する。
//! 処理の位置づけ: commandsまたはparsers/mod.rsから呼ばれ、外部ファイルとSequenceDataを相互変換する。

use crate::error::AppError;
use crate::models::{Annotation, DisplayShape, SequenceData, Strand, Topology};
use crate::utils::{clean_sequence, fix_localized_date};
use gb_io::reader::SeqReader as GbkReader;
use gb_io::seq::{After, Before, Feature, Location, Seq, Topology as GbkTopology};
use std::path::Path;

pub fn export_gbk(
    path: String,
    sequence: String,
    annotations: Vec<Annotation>,
    primers: Vec<crate::models::Primer>,
    topology: Topology,
) -> Result<(), AppError> {
    export_gbk_with_metadata(path, sequence, annotations, primers, topology, None, None)
}

pub fn export_gbk_with_metadata(
    path: String,
    sequence: String,
    annotations: Vec<Annotation>,
    primers: Vec<crate::models::Primer>,
    topology: Topology,
    id: Option<String>,
    description: Option<String>,
) -> Result<(), AppError> {
    crate::validation::validate_sequence_parts(&sequence, &annotations, &primers, &topology)?;
    let sequence_len = sequence.len();
    let locus_name = id
        .unwrap_or_default()
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                ch
            } else {
                '_'
            }
        })
        .collect::<String>();
    let locus_name = if locus_name.trim_matches('_').is_empty() {
        "GreenPeas_Export".to_string()
    } else {
        locus_name
    };
    let definition = description
        .unwrap_or_default()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    let definition = if definition.is_empty() {
        "Generated by GreenPeas - High Fidelity Export".to_string()
    } else {
        definition
    };

    let mut features: Vec<Feature> = annotations
        .into_iter()
        .map(|ann| {
            let location = export_location(ann.start, ann.end, ann.strand, sequence_len, &topology);

            let mut qualifiers = Vec::new();
            qualifiers.push((std::borrow::Cow::Borrowed("label"), Some(ann.name.clone())));
            if let Some(color) = ann.color {
                qualifiers.push((
                    std::borrow::Cow::Borrowed("note"),
                    Some(format!("color: {}", color)),
                ));
            }

            Feature {
                kind: std::borrow::Cow::Owned(ann.feature_type),
                location,
                qualifiers,
            }
        })
        .collect();

    // Export primers as primer_bind features
    for p in primers {
        let location = export_location(p.start, p.end, p.strand, sequence_len, &topology);

        let mut qualifiers = Vec::new();
        qualifiers.push((std::borrow::Cow::Borrowed("label"), Some(p.name.clone())));
        qualifiers.push((
            std::borrow::Cow::Borrowed("note"),
            Some(format!("sequence: {}", p.sequence)),
        ));
        if let Some(color) = p.color {
            qualifiers.push((
                std::borrow::Cow::Borrowed("note"),
                Some(format!("color: {}", color)),
            ));
        }

        features.push(Feature {
            kind: std::borrow::Cow::Borrowed("primer_bind"),
            location,
            qualifiers,
        });
    }

    let seq_topology = match topology {
        Topology::Circular => gb_io::seq::Topology::Circular,
        Topology::Linear => gb_io::seq::Topology::Linear,
    };

    let seq = Seq {
        name: Some(locus_name),
        topology: seq_topology,
        date: None,
        definition: Some(definition),
        accession: None,
        version: None,
        keywords: None,
        source: None,
        features,
        len: Some(sequence.len()),
        molecule_type: Some("ds-DNA".to_string()),
        seq: sequence.as_bytes().to_vec(),
        contig: None,
        comments: Vec::new(),
        dblink: None,
        division: "SYN".to_string(),
        references: Vec::new(),
    };

    crate::utils::atomic_write(Path::new(&path), |file| {
        seq.write(file)?;
        Ok(())
    })
}

fn export_location(
    start: usize,
    end: usize,
    strand: Strand,
    sequence_len: usize,
    topology: &Topology,
) -> Location {
    let forward = if matches!(topology, Topology::Circular) && start > end {
        Location::Join(vec![
            Location::Range(
                (start as i64, Before(false)),
                (sequence_len as i64, After(false)),
            ),
            Location::Range((0, Before(false)), (end as i64, After(false))),
        ])
    } else {
        Location::Range((start as i64, Before(false)), (end as i64, After(false)))
    };

    if strand == Strand::Reverse {
        Location::Complement(Box::new(forward))
    } else {
        forward
    }
}

pub fn list_gbk_sequences(path: String) -> Result<Vec<SequenceData>, AppError> {
    let data = std::fs::read(&path)?;
    let content = fix_localized_date(String::from_utf8_lossy(&data).to_string());
    validate_feature_qualifier_quotes(&content)?;
    let reader = GbkReader::new(std::io::Cursor::new(content.into_bytes()));

    let mut sequences = Vec::new();
    let file_id = std::path::Path::new(&path)
        .file_stem()
        .and_then(|s| s.to_str())
        .map(|s| s.to_string());

    for result in reader {
        let seq =
            result.map_err(|e: gb_io::reader::GbParserError| AppError::Parser(e.to_string()))?;

        let mut annotations = Vec::new();
        let mut primers = Vec::new();
        for (i, feature) in seq.features.iter().enumerate() {
            let mut feature_name_ref: Option<&str> = None;
            let mut color = None;
            let mut primer_sequence: Option<String> = None;
            let display_shape = Some(DisplayShape::Arrow);

            for (key, val_opt) in &feature.qualifiers {
                if let Some(val) = val_opt.as_deref() {
                    match key.as_ref() {
                        "label" | "gene" | "product" | "note" if feature_name_ref.is_none() => {
                            feature_name_ref = Some(val);
                        }
                        "color" | "colour" | "ApEinfo_fwdcolor" | "ApEinfo_revcolor" => {
                            color = Some(val.trim().trim_matches('"').to_string());
                        }
                        "note" => {
                            if feature.kind.as_ref() == "primer_bind" {
                                if let Some((_, sequence)) = val.split_once("sequence:") {
                                    primer_sequence = Some(sequence.trim().to_string());
                                }
                            }
                            if let Some((_, c)) = val.split_once("color:") {
                                let hex: String = c
                                    .trim()
                                    .chars()
                                    .take_while(|ch| ch.is_ascii_alphanumeric() || *ch == '#')
                                    .collect();
                                if !hex.is_empty() {
                                    color = Some(hex);
                                }
                            }
                        }
                        _ => {}
                    }
                }
            }

            let name = feature_name_ref
                .map(|s| s.to_string())
                .unwrap_or_else(|| feature.kind.to_string());

            let (start, end, strand) = parse_gb_location(&feature.location);

            if feature.kind.as_ref() == "primer_bind" {
                if let Some(sequence) = primer_sequence {
                    primers.push(crate::models::Primer {
                        id: format!("gb-primer-{}", i),
                        name,
                        sequence,
                        start,
                        end,
                        strand,
                        tail_5: String::new(),
                        tail_3: String::new(),
                        color,
                        mismatches: Vec::new(),
                    });
                } else {
                    annotations.push(Annotation {
                        id: format!("gb-{}", i),
                        name,
                        feature_type: feature.kind.to_string(),
                        start,
                        end,
                        strand,
                        color,
                        display_shape,
                    });
                }
            } else {
                annotations.push(Annotation {
                    id: format!("gb-{}", i),
                    name,
                    feature_type: feature.kind.to_string(),
                    start,
                    end,
                    strand,
                    color,
                    display_shape,
                });
            }
        }

        let topology = match seq.topology {
            GbkTopology::Circular => Topology::Circular,
            _ => Topology::Linear,
        };
        let sequence = clean_sequence(&String::from_utf8_lossy(&seq.seq));
        crate::algorithms::primer::reanalyze_all_primers(&sequence, &mut primers);

        sequences.push(SequenceData {
            id: file_id.clone().unwrap_or_else(|| {
                seq.name
                    .clone()
                    .unwrap_or_else(|| "GBK Sequence".to_string())
            }),
            description: seq.definition.clone(),
            sequence,
            annotations,
            primers,
            topology,
            trace: None,
            enzymes: None,
            enzyme_settings: None,
            alignment_results: None,
            debug_hex: None,
            file_path: Some(path.clone()),
        });
    }
    Ok(sequences)
}

fn validate_feature_qualifier_quotes(content: &str) -> Result<(), AppError> {
    let mut in_features = false;
    let mut quote_open = false;
    let mut quote_start_line = 0;

    for (index, line) in content.lines().enumerate() {
        let line_number = index + 1;
        if line.starts_with("FEATURES") {
            in_features = true;
            continue;
        }
        if line.starts_with("ORIGIN") || line.starts_with("//") {
            if quote_open {
                return Err(AppError::Parser(format!(
                    "Unclosed quoted GenBank feature qualifier starting on line {quote_start_line}"
                )));
            }
            in_features = false;
            continue;
        }
        if !in_features {
            continue;
        }

        let mut escaped = false;
        for character in line.chars() {
            if escaped {
                escaped = false;
            } else if character == '\\' {
                escaped = true;
            } else if character == '"' {
                quote_open = !quote_open;
                if quote_open {
                    quote_start_line = line_number;
                }
            }
        }
    }

    if quote_open {
        return Err(AppError::Parser(format!(
            "Unclosed quoted GenBank feature qualifier starting on line {quote_start_line}"
        )));
    }
    Ok(())
}

fn parse_gb_location(loc: &gb_io::seq::Location) -> (usize, usize, Strand) {
    match loc {
        gb_io::seq::Location::Range((s, _), (e, _)) => {
            ((*s).max(0) as usize, *e as usize, Strand::Forward)
        }
        gb_io::seq::Location::Complement(inner) => {
            let (s, e, _) = parse_gb_location(inner);
            (s, e, Strand::Reverse)
        }
        gb_io::seq::Location::Join(parts) | gb_io::seq::Location::Order(parts) => {
            if parts.is_empty() {
                return (0, 0, Strand::Forward);
            }
            let (first_s, first_e, first_str) = parse_gb_location(&parts[0]);
            let (last_s, last_e, last_str) = parse_gb_location(&parts[parts.len() - 1]);

            if parts.len() > 1 && last_s < first_s {
                // Circular wrap detected: e.g., join(2800..3000, 1..200)
                (
                    first_s,
                    last_e,
                    if first_str == Strand::Reverse || last_str == Strand::Reverse {
                        Strand::Reverse
                    } else {
                        Strand::Forward
                    },
                )
            } else {
                let mut min_s = first_s;
                let mut max_e = first_e;
                let mut strand = first_str;
                for p in parts {
                    let (ps, pe, pstr) = parse_gb_location(p);
                    min_s = min_s.min(ps);
                    max_e = max_e.max(pe);
                    if pstr == Strand::Reverse {
                        strand = Strand::Reverse;
                    }
                }
                (min_s, max_e, strand)
            }
        }
        _ => (0, 0, Strand::Forward),
    }
}

